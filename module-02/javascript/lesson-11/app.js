function calc(a, b, op) {

    if (op === "+") {
        return a + b;
    } else if (op === "-") {
        return a - b;
    } else if (op === "*") {
        return a * b;
    } else if (op === "/") {
        return a / b;
    }
}

let ans = calc(200, 220, "+");
console.log(ans);



