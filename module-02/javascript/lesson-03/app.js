// ============================================================================
// Operator Precedence & Associativity
// ============================================================================

// Operator Precedence (Highest → Lowest)
// ()      -> Parentheses
// **      -> Exponentiation (Right to Left)
// *, /, % -> Multiplication, Division, Modulus (Remainder)
// +, -    -> Addition, Subtraction

// -----------------------------------------------------------------------------
// Associativity
// -----------------------------------------------------------------------------
// When operators have the same precedence, JavaScript follows associativity.

// Left-to-Right:
// +, -, *, /, %

// Right-to-Left:
// ** (Exponentiation)

// Example:
// 2 ** 3 ** 2
// = 2 ** (3 ** 2)
// = 2 ** 9
// = 512

// ============================================================================
// Operator Precedence Example
// ============================================================================

// var result = (5 + 3) * 2 ** 3 ** 2 / 4 + 10 - 6 % 4;

// Step 1:
// (5 + 3) = 8

// Step 2:
// 2 ** 3 ** 2
// = 2 ** (3 ** 2)
// = 2 ** 9
// = 512

// Step 3:
// 8 * 512 = 4096

// Step 4:
// 4096 / 4 = 1024

// Step 5:
// 6 % 4 = 2

